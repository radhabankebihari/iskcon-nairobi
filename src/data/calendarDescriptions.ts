/** A short description for an observance, or undefined when nothing fits. */
export function describeObservance(event: string, type?: string): string | undefined {
  if (type === "Holiday") {
    return /moon sighting|eid/i.test(event)
      ? "Public holiday in Kenya. The date depends on the sighting of the moon."
      : HOLIDAY_DESCRIPTION;
  }

  // Checked before Ekadashi, since a break-fast entry names the Ekadashi it ends.
  if (/^break fast/i.test(event)) {
    return "The time window for breaking the previous day's Ekadashi fast.";
  }

  if (type === "Ekadashi" || /ekadashi|ekadasi/i.test(event)) {
    return ekadashiSpecial.find(([pattern]) => pattern.test(event))?.[1] ?? EKADASHI_DESCRIPTION;
  }

  const observance = observances.find(([pattern]) => pattern.test(event));
  if (observance) return observance[1];

  // For a day honouring several people, describe the first one named.
  const byPosition = persons
    .map(([pattern, text]) => ({ index: event.search(pattern), text }))
    .filter(({ index }) => index >= 0)
    .sort((a, b) => a.index - b.index);
  return byPosition[0]?.text;
}
